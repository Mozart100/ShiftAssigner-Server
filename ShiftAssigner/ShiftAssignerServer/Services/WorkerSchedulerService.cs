using ShiftAssignerServer.Models.WorkerScheduling;
using ShiftAssignerServer.Repositories;
using ShiftAssignerServer.Requests;
using ShiftAssignerServer.Services.Validation;

namespace ShiftAssignerServer.Services;

public interface IWorkerSchedulerService
{
    Task<ShiftPeriodScheduling> CreateNewWorkerRegisteringRequest(CreateShiftPeriodSchedulingRequest request, string shiftLeaderId);
    Task<WorkerShiftPeriodSchedulingResponse> GetWorkerShiftPeriodCurrentAndNextScheduling(string workerId);
}

public class WorkerSchedulerService : IWorkerSchedulerService
{
    private readonly ITenantUnitOfWork _tenantUnitOfWork;
    private readonly IWorkerSchedulerValidationService _validationService;

    public WorkerSchedulerService(ITenantUnitOfWork tenantUnitOfWork, IWorkerSchedulerValidationService validationService)
    {
        _tenantUnitOfWork = tenantUnitOfWork;
        _validationService = validationService;
    }

    public async Task<ShiftPeriodScheduling> CreateNewWorkerRegisteringRequest(CreateShiftPeriodSchedulingRequest request, string shiftLeaderId)
    {
        // Validate the request - this will throw ShiftAssignmentException if validation fails
        await _validationService.ValidateCreateShiftPeriodRequestAsync(request, shiftLeaderId);

        var config = await _tenantUnitOfWork.ShiftPeriodSchedulingRepository.GetAllAsync(x => x.IsActive && x.ShiftLeaderId.Equals(shiftLeaderId));

        var record = new ShiftPeriodScheduling
        {
            // Id is auto-generated by database
            ShiftLeaderId = shiftLeaderId,
            StartFrom = request.StartFrom,
            IsActive = true,
            Period = request.NextPeriod.Select(dayRequest => new ShiftPeriodScheduling.Day
            {
                DateOnly = dayRequest.Date,
                Shifts = dayRequest.Shifts.Select(shiftRequest => new ShiftPeriodScheduling.Day.ShiftInfo
                {
                    ShiftName = shiftRequest.ShiftName,
                    AmountOfWorkers = shiftRequest.AmountOfWorkers,
                    WorkerIds = new List<string>() // Initially empty, workers assigned later
                }).ToList()
            }).ToList()
        };

        await _tenantUnitOfWork.ShiftPeriodSchedulingRepository.InsertAsync(record);

        return record;
    }

    public async Task<WorkerShiftPeriodSchedulingResponse> GetWorkerShiftPeriodCurrentAndNextScheduling(string workerId)
    {
        // Get active shift periods where the worker is assigned
        var activeShiftPeriods = await _tenantUnitOfWork.ShiftPeriodSchedulingRepository
            .GetAllAsync(x => x.IsActive &&
                x.Period.Any(day => day.Shifts.Any(shift => shift.WorkerIds.Contains(workerId))));

        if (activeShiftPeriods.IsEmpty())
        {
            return new WorkerShiftPeriodSchedulingResponse
            {
                StartFrom = DateOnly.FromDateTime(DateTime.Now),
                Period = new List<WorkerShiftPeriodSchedulingResponse.CreateDaySchedule>(),
                Success = true,
                Message = "No active shift assignments found for worker"
            };
        }

        // Build the response with worker's assigned shifts from all active periods
        var workerDays = new List<WorkerShiftPeriodSchedulingResponse.CreateDaySchedule>();
        foreach (var period in activeShiftPeriods.OrderBy(x => x.StartFrom))
        {
            foreach (var day in period.Period)
            {
                var workerShifts = day.Shifts
                    .Where(shift => shift.WorkerIds.Contains(workerId))
                    .Select(shift => new WorkerShiftPeriodSchedulingResponse.CreateShiftInfo
                    {
                        ShiftName = shift.ShiftName
                    })
                    .ToList();

                if (workerShifts.Any())
                {
                    workerDays.Add(new WorkerShiftPeriodSchedulingResponse.CreateDaySchedule
                    {
                        Date = day.DateOnly,
                        Shifts = workerShifts
                    });
                }
            }
        }

        return new WorkerShiftPeriodSchedulingResponse
        {
            StartFrom = activeShiftPeriods.Min(x => x.StartFrom),
            Period = workerDays.OrderBy(d => d.Date).ToList(),
            Success = true,
            Message = "Worker shift schedule retrieved successfully"
        };
    }
}